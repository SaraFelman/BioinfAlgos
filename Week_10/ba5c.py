# 4 Find a Longest Common Subsequence of Two Strings
# Найдите самую длинную общую подпоследовательность двух строк
#
# Задача о наибольшей общей подпоследовательности
# Дано: Две строки.
# Возврат: самая длинная общая подпоследовательность этих строк.
#
# Sample Dataset
# AACCTTGG
# ACACTGTGA
# Sample Output
# AACTGG

# lsc - Longest Common Subsequence
def lcs(s1, s2):
    # Получаем длины входных строк
    m, n = len(s1), len(s2)

    # Создаём двумерный массив размером (m+1) на (n+1)
    # dp[i][j] будет хранить длину LCS для префиксов s1[0:i] и s2[0:j]
    dp = [[0] * (n + 1) for _ in range(m + 1)]

    # Заполняем таблицу построчно сверху вниз то есть перебираем префиксы первой строки от 1 до m;
    #   i соответствует префиксу s1[0:i] (первые i символов s1)
    for i in range(1, m + 1):
        # Заполняем таблицу по столбцам слева направо соответственно j соответствует префиксу s2[0:j]
        for j in range(1, n + 1):
            # Проверяем, совпадают ли последние символы текущих префиксов
            if s1[i - 1] == s2[j - 1]:
                # Если совпадают, то значит что они входят в LCS и длина LCS увеличивается на 1 по сравнению с префиксами без этих символов
                dp[i][j] = dp[i - 1][j - 1] + 1
            else: # Если нет, то LCS не включает оба этих символа одновременно
                # Берем максимальное значение из соседей слева и сверху
                dp[i][j] = max(dp[i - 1][j], dp[i][j - 1])

    # Создаем пустой список для сбора символов LCS в обратном порядке
    lcs_chars = []
    # Начинаем восстановление LCS с правого нижнего угла таблицы
    i, j = m, n

    # Идем по таблице назад, пока не достигнем границы
    while i > 0 and j > 0:
        # Если символы совпадают, они входят в LCS
        if s1[i - 1] == s2[j - 1]:
            # Добавляем символ в LCS (в обратном порядке)
            lcs_chars.append(s1[i - 1])
            # Переходим к диагональному элементу (вверх-влево)
            i -= 1
            j -= 1
        # Иначе идем в направлении большего значения в таблице
        elif dp[i - 1][j] > dp[i][j - 1]:
            # Идем вверх (игнорируем символ из первой строки)
            i -= 1
        else:
            # Идем влево (игнорируем символ из второй строки)
            j -= 1

    # Разворачиваем символы и объединяем в строку
    lcs_str = ''.join(reversed(lcs_chars))

    # Возвращаем наибольшую общую подпоследовательность
    return lcs_str

if __name__ == "__main__":
    # Вчитываем первую и вторую строки из ввода, находим наибольшую общую подпоследовательность, выводим результат
    s1 = input().strip()
    s2 = input().strip()

    result = lcs(s1, s2)
    print(result)